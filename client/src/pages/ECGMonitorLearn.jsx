import { useNavigate } from "react-router-dom";
import { useState } from "react";

function ECGMonitorLearn() {
  const navigate = useNavigate();

  const [completed, setCompleted] = useState(
    localStorage.getItem("ecgMonitorLearn") === "completed"
  );

  const handleFinishLearning = () => {
    localStorage.setItem("ecgMonitorLearn", "completed");
    setCompleted(true);
  };

  return (
    <div className="min-h-screen bg-slate-100 py-12 px-6">
      <div className="max-w-5xl mx-auto">

        {/* Back Button */}
        <button
          onClick={() => navigate("/ecg-monitor")}
          className="mb-6 text-blue-600 font-semibold hover:underline"
        >
          ← Back to ECG Monitor Dashboard
        </button>

        {/* Header */}
        <div className="bg-white rounded-2xl shadow-lg p-8 mb-8">
          <h1 className="text-4xl font-bold text-blue-700 mb-3">
            ECG Monitor – Learning Module
          </h1>

          <p className="text-gray-600 text-lg">
            Learn about the purpose, working principle, components,
            operating procedure, and safety precautions of an ECG Monitor.
          </p>
        </div>

        {/* 1. What is ECG Monitor */}
        <Section title="1. What is an ECG Monitor?">
          <p>
            An ECG (Electrocardiogram) Monitor is a medical device used
            to record and display the electrical activity of the heart.
            It helps healthcare professionals observe the heart rate,
            heart rhythm, and electrical activity of the heart.
          </p>
        </Section>

        {/* 2. Purpose */}
        <Section title="2. Purpose of an ECG Monitor">
          <ul className="list-disc pl-6 space-y-2">
            <li>To record the electrical activity of the heart.</li>
            <li>To display the ECG waveform.</li>
            <li>To monitor heart rate and rhythm.</li>
            <li>To observe abnormal cardiac activity.</li>
            <li>To support continuous cardiac monitoring.</li>
          </ul>
        </Section>

        {/* 3. Working Principle */}
        <Section title="3. Working Principle">
          <div className="space-y-4">

            <p>
              The ECG Monitor detects the small electrical signals
              generated by the heart during cardiac activity.
            </p>

            <p>
              Electrodes placed on the patient's body detect these
              electrical signals. The signals are then amplified to
              increase their strength and passed through filters to
              reduce unwanted noise and interference.
            </p>

            <p>
              The conditioned analog signal is converted into a digital
              signal using an Analog-to-Digital Converter (ADC). The
              digital signal is then processed by the main controller
              and the ECG waveform is displayed on the monitor.
            </p>

            <div className="bg-blue-50 border border-blue-200 rounded-xl p-5 text-center">
              <p className="font-bold text-blue-700">
                ECG Electrodes → Amplifier → Signal Filter → ADC → Main Controller → Display
              </p>
            </div>

          </div>
        </Section>

        {/* 4. Components */}
        <Section title="4. Major Components of an ECG Monitor">
          <div className="space-y-4">

            <ComponentItem
              name="1. ECG Electrodes"
              description="Detect the electrical signals produced by the heart."
            />

            <ComponentItem
              name="2. ECG Amplifier"
              description="Amplifies the weak electrical signals obtained from the electrodes."
            />

            <ComponentItem
              name="3. Signal Filter"
              description="Reduces unwanted noise and interference from the ECG signal."
            />

            <ComponentItem
              name="4. Analog-to-Digital Converter (ADC)"
              description="Converts the analog ECG signal into a digital signal for further processing."
            />

            <ComponentItem
              name="5. Main Controller"
              description="Processes the digital ECG signal and controls the operation of the monitoring system."
            />

            <ComponentItem
              name="6. Display"
              description="Displays the ECG waveform and related monitoring information."
            />

          </div>
        </Section>

        {/* 5. Electrodes and Leads */}
        <Section title="5. ECG Electrodes and Leads">
          <p>
            ECG electrodes are used to detect the electrical activity
            of the heart from the patient's body. The electrodes are
            connected to the ECG Monitor through lead wires.
            Proper electrode placement and correct lead connection
            are important for obtaining a reliable ECG signal.
          </p>
        </Section>

        {/* 6. Operating Procedure */}
        <Section title="6. Basic Operating Procedure">
          <ol className="list-decimal pl-6 space-y-2">
            <li>Prepare the ECG Monitor and required accessories.</li>
            <li>Prepare the patient for ECG monitoring.</li>
            <li>Place the electrodes at the appropriate locations.</li>
            <li>Connect the ECG leads correctly.</li>
            <li>Switch on the ECG Monitor.</li>
            <li>Check the ECG waveform on the display.</li>
            <li>Observe the heart rate and rhythm.</li>
            <li>Check that the ECG signal is stable.</li>
          </ol>
        </Section>

        {/* 7. Safety */}
        <Section title="7. Safety Precautions">
          <ul className="list-disc pl-6 space-y-2">
            <li>Ensure proper electrode placement.</li>
            <li>Check all ECG lead connections before use.</li>
            <li>Do not use damaged cables or electrodes.</li>
            <li>Ensure good contact between electrodes and the patient.</li>
            <li>Keep the electrode contact area clean.</li>
            <li>Minimize unnecessary patient movement.</li>
            <li>Follow the manufacturer's operating instructions.</li>
          </ul>
        </Section>

        {/* 8. Common Problems */}
        <Section title="8. Common ECG Monitoring Problems">
          <ul className="list-disc pl-6 space-y-2">
            <li>ECG waveform not displayed.</li>
            <li>Excessive noise in the ECG signal.</li>
            <li>Weak ECG signal.</li>
            <li>Incorrect electrode or lead connection.</li>
            <li>Digital ECG signal not available.</li>
            <li>Display-related problems.</li>
          </ul>
        </Section>

        {/* 9. Learning Summary */}
        <Section title="9. Learning Summary">
          <p>
            In this module, students learn the purpose and working
            principle of an ECG Monitor, the major components involved
            in ECG signal acquisition and processing, the basic
            operating procedure, and important safety precautions.
          </p>

          <p className="mt-4">
            This knowledge provides the foundation for the next
            interactive Practice module, where students can practice
            ECG electrode and lead placement.
          </p>
        </Section>

        {/* Completion Section */}
        <div className="bg-white rounded-2xl shadow-lg p-8 mt-8 text-center">

          {completed && (
            <div className="bg-green-100 border border-green-300 rounded-xl p-4 mb-6">
              <p className="text-green-700 font-bold text-lg">
                ✓ Learning Module Completed
              </p>

              <p className="text-green-600 text-sm mt-1">
                You can review this learning module again anytime.
              </p>
            </div>
          )}

          <h2 className="text-2xl font-bold text-gray-800 mb-3">
            {completed
              ? "Review the Learning Module"
              : "Complete the Learning Module"}
          </h2>

          <p className="text-gray-600 mb-6">
            {completed
              ? "You have already completed this module. You can read the topics again and review the concepts."
              : "Read and understand all the topics before completing the ECG Monitor Learning Module."}
          </p>

          {/* Finish / Complete Again */}
          <button
            onClick={handleFinishLearning}
            className="bg-blue-600 hover:bg-blue-700 text-white px-8 py-3 rounded-lg font-bold transition"
          >
            {completed
              ? "✓ Complete Learning Again"
              : "✓ Finish Learning"}
          </button>

          {/* Dashboard */}
          <div className="mt-4">
            <button
              onClick={() => navigate("/ecg-monitor")}
              className="bg-gray-600 hover:bg-gray-700 text-white px-8 py-3 rounded-lg font-bold transition"
            >
              🏠 Back to ECG Monitor Dashboard
            </button>
          </div>

        </div>

      </div>
    </div>
  );
}


/* =====================================================
   SECTION COMPONENT
===================================================== */

function Section({ title, children }) {
  return (
    <div className="bg-white rounded-2xl shadow-md p-7 mb-6">

      <h2 className="text-2xl font-bold text-blue-700 mb-4">
        {title}
      </h2>

      <div className="text-gray-700 leading-7 text-lg">
        {children}
      </div>

    </div>
  );
}


/* =====================================================
   COMPONENT ITEM
===================================================== */

function ComponentItem({ name, description }) {
  return (
    <div className="bg-slate-50 border border-slate-200 rounded-lg p-4">

      <h3 className="font-bold text-gray-800 text-lg">
        {name}
      </h3>

      <p className="text-gray-600 mt-1">
        {description}
      </p>

    </div>
  );
}

export default ECGMonitorLearn;